# NEW (not a lab file, 2026-11-23): build the high/low exposure assignment for compare_te_cyp_*.py
# from the ecology workbook (Google Sheet "Drosophilid dataset (datasets_dhakad) - Ecology, Phylogeny &
# Pest/Insecticide Status", exported to input/ecology/drosophilid-ecology-exposure.xlsx).
#
# Rule, on sheet 3 col E "Insecticide exposure" (the sheet's own graded call, see its sheet 4):
#   high = "Documented exposure ..." (sprayed, 7 taxa) or "Likely" (breeds in treated habitat)
#   low  = "Unlikely" or "Very unlikely" (wild habitat, no insecticide use)
#   none = "Possible", "Possible to likely, as a non-target organism", "Unknown" -> left out of the test
# Rows the sheet says to keep out of any statistical comparison (the 10 unresolved names, col E
# "Unknown") are left out. Host-toxin confounders (cactophiles, mycophages, D. sechellia: their
# detox genes track plant/fungal toxins, sheet 8 table 4) stay in "low" but are flagged.
#
# Writes exposure.tsv (every species in pairs.tsv) and species_config.ini (high/low only, the
# format compare_te_cyp_exposure.py reads; gff = the combined GFF3 build_tfbs_te_gff.py will write).
# Run: nix-shell -p 'python3.withPackages(p: [p.openpyxl])' --run 'python3 make-exposure.py'
import csv, re, collections, openpyxl
H = "/bioinformatics/atallah-repeats/4-combine-and-compare"
PAIRS = "/bioinformatics/atallah-repeats/3-pair-te-with-cyp/pairs.tsv"
COMBINED = f"{H}/output/combined-gff"

def norm(s):
    s = re.split(r"\.(GC[AF]_|nanopore)", str(s))[0]
    return re.sub(r"_+", "_", re.sub(r"[^A-Za-z0-9]+", "_", s)).strip("_").upper()

def group(e):
    e = (e or "").strip()
    if e.startswith("Documented exposure") or e == "Likely": return "high"
    if e in ("Unlikely", "Very unlikely"): return "low"
    return "none"

CONFOUND = {"Necrotic cactus", "Cactus-rot-soaked desert soil", "Fungi (wild)"}
wb = openpyxl.load_workbook(f"{H}/input/ecology/drosophilid-ecology-exposure.xlsx", read_only=True, data_only=True)
rows = list(wb["3. Pest & insecticide status"].iter_rows(values_only=True))
hdr, sheet = rows[0], {}
for r in rows[1:]:
    if r[0]: sheet.setdefault(norm(r[0]), r)

pairs = [r for r in csv.DictReader(open(PAIRS), delimiter="\t") if r["status"] == "RUN"]
out, miss = [], []
for p in pairs:
    lab = p["gff_label"]
    r = sheet.get(norm(p["rm_sample"])) or sheet.get(lab)
    if r is None:
        miss.append(lab); out.append(dict(gff_label=lab, rm_sample=p["rm_sample"], exposure="none", rule="not in ecology sheet")); continue
    g = group(r[4])
    conf = "host-toxin confounder: " + r[6] if (r[6] in CONFOUND or "sechellia" in str(r[0])) else ""
    out.append(dict(gff_label=lab, rm_sample=p["rm_sample"], sheet_label=r[0], exposure=g,
                    insecticide_exposure=r[4], exposure_route=r[10], exposure_setting=r[17],
                    direct_vs_incidental=r[18], resistance_evidence=r[19], pest=r[2], confounder=conf,
                    rule=f"col E '{r[4]}' -> {g}"))
cols = ["gff_label", "rm_sample", "sheet_label", "exposure", "insecticide_exposure", "exposure_route",
        "exposure_setting", "direct_vs_incidental", "resistance_evidence", "pest", "confounder", "rule"]
with open(f"{H}/exposure.tsv", "w", newline="") as o:
    w = csv.DictWriter(o, fieldnames=cols, delimiter="\t", restval="", lineterminator="\n"); w.writeheader(); w.writerows(out)
with open(f"{H}/species_config.ini", "w") as o:
    o.write("# Generated by make-exposure.py from exposure.tsv (high/low only). Do not edit by hand.\n"
            "# gff = combined GFF3 from build_tfbs_te_gff.py; those files are written by the stage 4 build.\n\n")
    for x in out:
        if x["exposure"] in ("high", "low"):
            o.write(f"[{x['gff_label']}]\ngff = {COMBINED}/{x['gff_label']}.combined.gff3\nexposure = {x['exposure']}\n\n")
c = collections.Counter(x["exposure"] for x in out)
print("species:", len(out), dict(c), "| not in sheet:", miss)
print("high:", sorted(x["gff_label"] for x in out if x["exposure"] == "high"))
print("low with confounder flag:", sum(1 for x in out if x["exposure"] == "low" and x["confounder"]))
